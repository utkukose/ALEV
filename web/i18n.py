LOCALES = {"tr": TR, "en": EN}

def get_lang(request: Request) -> str:
    cookie = request.cookies.get("lang","")
    if cookie in LOCALES: return cookie
    accept = request.headers.get("accept-language","")
    return "en" if accept.lower().startswith("en") else "tr"

def get_t(request: Request):
    lang = get_lang(request)
    data = LOCALES.get(lang, TR)
    def ns(d):
        if isinstance(d, dict): return SimpleNamespace(**{k: ns(v) for k,v in d.items()})
        return d
    return ns(data)

def available_langs():
    return [{"code": k} for k in LOCALES]
